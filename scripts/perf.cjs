/**
 * P5.6 performance check (npm run perf). Boots nothing: point PERF_BASE_URL at a running server.
 * Profiles: "low-end phone" = CPU 4× slower; networks = DevTools Regular 2G, Good 3G, and unthrottled.
 * Measures first contentful paint, DOMContentLoaded, load and bytes transferred (cold cache), then a warm reload.
 * Writes docs/PERFORMANCE.md. Honest numbers — nothing is extrapolated.
 */
const { chromium } = require("playwright");
const fs = require("fs");
const BASE = process.env.PERF_BASE_URL || "http://localhost:5000";
const NETS = {
  "Regular 2G": { offline: false, latency: 300, downloadThroughput: (250 * 1024) / 8, uploadThroughput: (50 * 1024) / 8 },
  "Good 3G": { offline: false, latency: 40, downloadThroughput: (1.5 * 1024 * 1024) / 8, uploadThroughput: (750 * 1024) / 8 },
  "No throttling": { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 },
};
const PAGES = [["Citizen app (web)", "/"], ["Department portal", "/web/dept"], ["Command portal", "/web/portal"], ["Privacy notice", "/web/privacy"]];

async function measure(browser, url, net) {
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  const cdp = await ctx.newCDPSession(page);
  await cdp.send("Network.enable");
  await cdp.send("Network.emulateNetworkConditions", NETS[net]);
  await cdp.send("Emulation.setCPUThrottlingRate", { rate: 4 });
  let bytes = 0;
  cdp.on("Network.loadingFinished", e => { bytes += e.encodedDataLength; });
  const t0 = Date.now();
  await page.goto(BASE + url, { waitUntil: "load", timeout: 300000 });
  const load = Date.now() - t0;
  const nav = await page.evaluate(() => {
    const n = performance.getEntriesByType("navigation")[0];
    const fcp = performance.getEntriesByName("first-contentful-paint")[0];
    return { dcl: Math.round(n.domContentLoadedEventEnd), fcp: fcp ? Math.round(fcp.startTime) : null };
  });
  const cold = bytes;
  bytes = 0;
  const t1 = Date.now();
  await page.reload({ waitUntil: "load", timeout: 300000 });
  const warm = Date.now() - t1;
  await ctx.close();
  return { load, ...nav, kb: Math.round(cold / 1024), warm, warmKb: Math.round(bytes / 1024) };
}

(async () => {
  const browser = await chromium.launch();
  const rows = [];
  for (const [name, url] of PAGES) for (const net of Object.keys(NETS)) {
    const r = await measure(browser, url, net);
    rows.push({ name, net, ...r });
    console.log(`${name.padEnd(20)} ${net.padEnd(14)} FCP ${r.fcp} ms · load ${r.load} ms · ${r.kb} KB · warm ${r.warm} ms (${r.warmKb} KB)`);
  }
  await browser.close();
  const bundle = fs.readdirSync("static-build/web/_expo/static/js/web").filter(f => f.endsWith(".js")).map(f => fs.statSync(`static-build/web/_expo/static/js/web/${f}`).size).reduce((a, b) => a + b, 0);
  const md = [
    "# Performance report (P5.6)", "",
    `Generated by \`npm run perf\` on ${new Date().toISOString().slice(0, 10)} against ${BASE}. CPU throttled 4× (low-end phone profile), cold cache unless noted.`, "",
    `Web bundle: ${(bundle / 1048576).toFixed(2)} MB JavaScript before gzip (served gzipped; content-hashed files cached for 1 year).`, "",
    "| Page | Network | First paint | Load | Transferred (cold) | Warm reload |", "|---|---|---|---|---|---|",
    ...rows.map(r => `| ${r.name} | ${r.net} | ${r.fcp ?? "—"} ms | ${r.load} ms | ${r.kb} KB | ${r.warm} ms (${r.warmKb} KB) |`), "",
  ].join("\n");
  fs.writeFileSync("docs/PERFORMANCE.md", md + "\n");
})().catch(e => { console.error(e); process.exit(1); });
